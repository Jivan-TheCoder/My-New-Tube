    fun getDefaultCdnBase(): String = decrypt(encryptedCdnBase)

    fun getDefaultRawBase(): String = decrypt(encryptedRawBase)

    private fun decrypt(encrypted: ByteArray): String {
        val decrypted = ByteArray(encrypted.size)
        for (i in encrypted.indices) {
            decrypted[i] = (encrypted[i].toInt() xor KEY[i % KEY.length].code).toByte()
        }
        return String(decrypted, Charsets.UTF_8)
    }
}
